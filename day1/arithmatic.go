package day1

import "fmt"

func Arithmatic() {
	var a, b int
	fmt.Println("Enter the first number:")
	fmt.Scan(&a)
	fmt.Println("Enter the second number:")
	fmt.Scan(&b)
	fmt.Println("a+b:", a+b)
	fmt.Println("a-b:", a-b)
	fmt.Println("a*b:", a*b)
	fmt.Println("a/b:", a/b)
	fmt.Println("a%b:", a%b)

}
